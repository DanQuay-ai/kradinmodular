VOW = ["a", "e", "ɛ", "i", "o", "ɔ", "u"]
ROWS = ["", "p", "t", "d", "k", "f", "s", "n", "r"]

def build():
    out = {}
    for on in ROWS:
        for v in VOW:
            k = on + v
            u = USER.get(k)
            if u and u.get("approved"):
                out[k] = {"strokes": u["strokes"], "status": "approved"}
            elif k in D:
                out[k] = {"strokes": [rnd(s) for s in D[k]], "status": "draft"}
            elif u:
                out[k] = {"strokes": u["strokes"], "status": "draft"}
    return out

