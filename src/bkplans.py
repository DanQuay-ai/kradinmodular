"""Arnold Böcklin, letter by letter, as standard parts.

Each letter is a short list of parts. A part is a line through a few points: u runs across the letter's ink box
(0 = left, 1 = right), y is in design units (baseline 0, x-height 516, cap 700, descender -200).
Kinds:  s = stroke (stem, bowl, arch, swash...), b = thin bar, f = foot (the brush foot with two spurs, one shape
for the whole font), and over=True marks a stroke that passes over what is drawn before it with a white halo.
The fitter moves these points and widths to the reference; the shapes stay these few clean lines."""

X, C = 516, 700


def S(*pts, over=False): return ("s", list(pts), over)
def B(*pts, over=False): return ("b", list(pts), over)
def F(u, y=0): return ("f", [(u - 0.15, y + 14), (u + 0.15, y + 14)], False)
def O(y0, y1, cx=0.5): return ("s", [(cx, y1), (0.05, (y0 + y1) / 2), (cx, y0), (0.95, (y0 + y1) / 2), (cx, y1)], False)


